/**
 * The quest catalogue.
 *
 * ## How the main line is built
 *
 * Each main quest unlocks the next by naming it in `unlock`, so the chain is data rather than
 * code: the engine moves a quest from locked to active the moment the one before it is claimed,
 * and nothing else has to know the order. `next` names what a claim opens, which is what the
 * panel shows as "mở khóa".
 *
 * The line follows what the game actually gates on — plant, care, a first stage, level 3, a
 * first breed, the first boss, ten stages, level 5 — so the quest that says "đạt cấp 3" is the
 * quest that opens the thing level 3 opens. A guide that promises something the game does not do
 * is worse than no guide.
 *
 * ## Why some quests read `current` and some do not
 *
 * A quest whose measure is a fact about the save — your level, how many stages you have cleared,
 * how many species you hold — reads it directly, so it is correct the moment it opens and repairs
 * itself if an event was missed. A quest that means "do this *now*" — run a combo, replay a
 * cleared stage — has no `current` on purpose: it can only be earned by the event.
 */

